#  کمکیِ درج: افزودنِ بخش‌های نو با حفظِ «نتیجه‌گیری» در انتها
# ═════════════════════════════════════════════════════════════════════════════
def insert_keep_conclusion_last(chapter, new_secs, existing_nums):
    """بخش‌های نو را می‌افزاید و بخشِ نتیجه‌گیری را به انتهای فصل منتقل می‌کند."""
    secs = chapter["sections"]
    # فقط بخش‌هایی که هنوز نیستند
    to_add = [s for s in new_secs if s["num"] not in existing_nums]
    concl_idx = next((i for i, s in enumerate(secs)
                      if "نتیجه‌گیری" in s.get("title_fa", "")), None)
    if concl_idx is None:
        secs.extend(to_add)
    else:
        concl = secs.pop(concl_idx)
        secs.extend(to_add)
        secs.append(concl)
    return len(to_add)


