def _paras_of(ch, *keys):
    """پاراگراف‌های نخستین بخشی که عنوانش شاملِ یکی از کلیدواژه‌هاست."""
    for s in ch.get("sections", []):
        t = s.get("title_fa", "")
        if any(k in t for k in keys):
            return list(s.get("paras", []))
    return []


def _sec_of(ch, *keys):
    """نخستین بخشی که عنوانش شاملِ یکی از کلیدواژه‌هاست (کلِ دیکشنری)."""
    for s in ch.get("sections", []):
        t = s.get("title_fa", "")
        if any(k in t for k in keys):
            return s
    return None


def _fix_fn_markers(section):
    """هر نشانگرِ {{fn:N}} که به پانویسِ موجود در همین بخش اشاره نکند حذف می‌شود
    تا ارجاعِ یتیم (orphan) در سند و وب پدید نیاید."""
    fns = section.get("fns") or []
    n = len(fns)
    def repl(m):
        idx = int(m.group(1))
        return m.group(0) if 1 <= idx <= n else ""
    section["paras"] = [re.sub(r"\{\{fn:(\d+)\}\}", repl, p) for p in section.get("paras", [])]
    return section


