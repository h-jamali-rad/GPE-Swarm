ZWNJ = "\u200c"
_PUNCT_FA = "،؛؟!:.»)"
def normalize_fa_typography(t):
    if not isinstance(t, str):
        return t
    # فاصله‌های چندگانه → یک فاصله
    t = re.sub(r"[ \t]{2,}", " ", t)
    # حذف فاصله پیش از علائم نگارشیِ بستنی
    t = re.sub(r"\s+([،؛؟!.:])", r"\1", t)
    # حذف فاصله پس از پرانتز/گیومهٔ باز و پیش از بستن
    t = re.sub(r"«\s+", "«", t)
    t = re.sub(r"\s+»", "»", t)
    t = re.sub(r"\(\s+", "(", t)
    t = re.sub(r"\s+\)", ")", t)
    # افزودن یک فاصله پس از علامتِ فارسی اگر بلافاصله حرف آمده باشد (نه در اعداد)
    t = re.sub(r"([،؛])(?=[^\s\d۰-۹])", r"\1 ", t)
    # نیم‌فاصلهٔ پیشوند/پسوندهای پرکاربرد
    t = re.sub(r"\bمی (?=[آ-ی])", "می" + ZWNJ, t)
    t = re.sub(r"\bنمی (?=[آ-ی])", "نمی" + ZWNJ, t)
    t = t.replace(" ها ", "\u200cها ").replace(" های ", "\u200cهای ")
    t = t.replace(" تر ", "\u200cتر ").replace(" ترین ", "\u200cترین ")
    return t.strip()

def deep_apply(thesis, fn_text):
    """اعمالِ یک تابعِ متن‌به‌متن بر همهٔ رشته‌های محتوایی رساله."""
    def fix(s):
        return fn_text(s) if isinstance(s, str) else s
    m = thesis.get("meta", {})
    for k in list(m.keys()):
        m[k] = fix(m[k])
    for ch in thesis["chapters"]:
        for key in ("title_fa", "summary_fa", "status_fa", "cap_fa"):
            if key in ch:
                ch[key] = fix(ch[key])
        for sec in ch["sections"]:
            sec["title_fa"] = fix(sec.get("title_fa", ""))
            sec["paras"] = [fix(p) for p in sec.get("paras", [])]
            sec["fns"] = [fix(f) for f in sec.get("fns", [])]
    # واژه‌نامه، مناظره، روش‌شناسی
    for g in thesis.get("glossary", []):
        for k in ("def_fa", "source_fa"):
            if k in g:
                g[k] = fix(g[k])



