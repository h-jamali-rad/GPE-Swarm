def get_chapter(thesis, num_fa):
    return next((c for c in thesis["chapters"] if c["num"] == num_fa), None)

def has_section(chapter, num=None, title_contains=None):
    for s in chapter.get("sections", []):
        if num and s.get("num") == num:
            return True
        if title_contains and title_contains in s.get("title_fa", ""):
            return True
    return False

def new_section(num, level, title, paras, fns=None, sources=None):
    return {
        "num": num, "level": level, "title_fa": title, "status": "written",
        "paras": paras, "fns": fns or [], "sources": sources or [],
    }

