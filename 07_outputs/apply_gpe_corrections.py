FA_D = "۰۱۲۳۴۵۶۷۸۹"
_FA2EN = {ord(f): str(i) for i, f in enumerate(FA_D)}
def _numtuple(num):
    if not num:
        return (999,)
    parts = str(num).translate(_FA2EN).split("-")
    try:
        return tuple(int(p) for p in parts if p != "")
    except ValueError:
        return (998,)


def reorder_ch4(thesis):
    """مرتب‌سازیِ عددیِ بخش‌های فصل چهارم با نگه‌داشتنِ «نتیجه‌گیری» در انتها."""
    ch4 = get_chapter(thesis, "فصل ۴") or get_chapter(thesis, "فصل چهارم")
    if not ch4:
        return False
    secs = ch4["sections"]
    secs.sort(key=lambda s: (1 if "نتیجه‌گیری" in s.get("title_fa", "") else 0,
                             _numtuple(s.get("num"))))
    ch4["sections"] = secs
    return True


def recompute_stats(thesis):
    """به‌روزرسانیِ شمارگانِ فصل‌ها پس از افزودن/بازآراییِ بخش‌ها."""
    for c in thesis.get("chapters", []):
        secs = c.get("sections", [])
        c["stat_sections"] = len(secs)
        c["stat_paras"] = sum(len(s.get("paras", [])) for s in secs)
        c["stat_fns"] = sum(len(s.get("fns", [])) for s in secs)
        if "count" in c:
            c["count"] = len(secs)


