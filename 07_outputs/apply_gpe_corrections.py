#  ممیزیِ منابع: حذفِ تکرار و حفظِ نشانِ پیش‌چاپِ داوری‌نشده (بندهای ۶۲–۶۵)
# ═════════════════════════════════════════════════════════════════════════════
def _norm_ref(t):
    t = re.sub(r"\(\d{4}\)|،?\s*\d{4}\.?", " ", str(t))     # حذفِ سال
    t = re.sub(r"[«».,;:()\[\]\-–—/]", " ", t)
    t = re.sub(r"\s+", " ", t).strip().lower()
    return t[:80]


def audit_references(thesis):
    refs = thesis.get("references")
    if not isinstance(refs, dict):
        return 0
    removed = 0
    for lang in ("fa", "en"):
        lst = refs.get(lang) or []
        seen = {}
        out = []
        for r in lst:
            key = _norm_ref(r.get("text", ""))
            if key and key in seen:
                # ادغام: اگر یکی cited بود، cited بماند
                if r.get("cited"):
                    seen[key]["cited"] = True
                removed += 1
                continue
            seen[key] = r
            out.append(r)
        refs[lang] = out
    return removed


