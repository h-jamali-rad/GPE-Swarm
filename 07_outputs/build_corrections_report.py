def main():
    doc = Document(); B.build_styles(doc)
    sec = doc.sections[0]
    sec.page_height = Mm(297); sec.page_width = Mm(210)
    sec.top_margin = Mm(30); sec.bottom_margin = Mm(28)
    sec.right_margin = Mm(28); sec.left_margin = Mm(28)
    B.set_rtl_section(doc)
    fns = B.Footnotes(doc)

    # ── cover ──
    for _ in range(3):
        doc.add_paragraph()
    R.banner(doc, "گزارشِ اجرای اصلاحاتِ رساله", fill=NAVY, fa_pt=24, after=0)
    R.banner(doc, "پاسخ به گزارشِ جامعِ بررسیِ تطبیقیِ نسخهٔ اول و دوم (۹۰ بند)", fill="1c4a63", fa_pt=14, after=0)
    R.banner(doc, "سندِ شفافیتِ اجرا: از ملاحظه تا اعمال", fill=GOLD, fg="1a1205", fa_pt=13, after=6)
    for _ in range(6):
        doc.add_paragraph()
    R.hr(doc)
    B.center_para(doc, "تهیه‌شده توسطِ سامانهٔ هوشمندِ پژوهش (Project Brain)", fa_pt=12, after=4)
    B.center_para(doc, FOOTER, fa_pt=11, after=4)
    doc.add_page_break()

    # ── intro ──
    R.heading_bar(doc, "مقدمه: روشِ اجرا و دامنهٔ صداقتِ علمی", fa_pt=16, before=0)
    for para in INTRO:
        B.add_para(doc, fns, para, fa_pt=14, indent=6)
    doc.add_page_break()

    # ── per-chapter corrections ──
    for title, color, items in GROUPS:
        R.heading_bar(doc, title, fill=color, fa_pt=15, before=0)
        for name, desc in items:
            R.subheading(doc, name)
            B.add_para(doc, fns, desc, fa_pt=14, indent=6)
        R.hr(doc)

    # ── closing ──
    doc.add_paragraph()
    R.heading_bar(doc, "برآیند و تأکیدِ پایانی", fa_pt=16, before=0)
    for para in CLOSING:
        B.add_para(doc, fns, para, fa_pt=14, indent=6)

    doc.add_paragraph()
    R.hr(doc)
    B.center_para(doc, FOOTER, fa_pt=11, after=4)

    fns.finalize()
    B.enable_update_fields(doc)
    doc.save(OUT)
    print("WROTE", OUT, os.path.getsize(OUT), "bytes; footnotes:", len(fns.items))


if __name__ == "__main__":
    main()
